// A centralized service class providing static and instance methods for
// log dispatching, channel filtering, and defense tag formatting.
// ============================================================================

export class CombatLogService {
  /**
   * Builds an enriched combat log entry with structured defense metadata.
   */
  static createDamageLogEntry(params: {
    caster?: CombatCharacter | null;
    target: CombatCharacter;
    baseDamage: number;
    damageType: string;
    sourceName?: string;
    isCritical?: boolean;
    isDeath?: boolean;
    zoneContext?: ResistanceZoneContext;
  }): CombatLogEntry {
    const {
      caster,
      target,
      baseDamage,
      damageType,
      sourceName = 'Attack',
      isCritical = false,
      isDeath = false,
      zoneContext,
    } = params;

    const breakdown = calculateDefenseBreakdown(
      baseDamage,
      damageType,
      target,
      caster,
      undefined,
      zoneContext
    );

    const critText = isCritical ? ' [Critical!]' : '';
    const tagSuffix = breakdown.tagString ? ` ${breakdown.tagString}` : '';
    const attackerName = caster?.name ?? 'An attacker';
    const deathText = isDeath ? ' and is defeated!' : '';

    const message = `${target.name} takes ${breakdown.finalDamage} ${damageType} damage from ${attackerName} (${sourceName})${critText}${tagSuffix}${deathText}`;

    // CMB-GAP-003: this emitter knows exactly what happened, so it states the event class
    // rather than leaving the adapter to recover it from the sentence it just built.
    const eventClass = isDeath
      ? CombatEventClass.KILL
      : isCritical
        ? CombatEventClass.CRITICAL_DAMAGE
        : CombatEventClass.DAMAGE;

    return {
      id: `log_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
      timestamp: Date.now(),
      type: 'damage',
      eventClass,
      message,
      characterId: target.id,
      targetIds: [target.id],
      data: {
        damage: baseDamage,
        damageAmount: breakdown.finalDamage,
        damageType,
        damageDealt: breakdown.finalDamage,
        source: caster?.name,
        sourceCharacterId: caster?.id,
        targetCharacterId: target.id,
        isCrit: isCritical,
        isCritical,
        isDeath,
        isResisted: breakdown.isResistant,
        resistanceApplied: breakdown.effectiveResistance,
        resistedDamageType: breakdown.effectiveResistance ? damageType : undefined,
        isVulnerable: breakdown.isVulnerable,
        vulnerabilityApplied: breakdown.isVulnerable,
        vulnerableDamageType: breakdown.isVulnerable ? damageType : undefined,
        isImmune: breakdown.isImmune,
        immunityApplied: breakdown.isImmune,
        immuneDamageType: breakdown.isImmune ? damageType : undefined,
        defenseTags: breakdown.tags,
        channel: 'damage',
      },
    };
  }

  /**
   * Helper to classify a log entry into its channel.
   */
  static classifyChannel(entry: CombatLogEntry): CombatLogChannel {
    return classifyLogEntryChannel(entry);
  }

  /**
   * Helper to filter log entries.
   */
  static filterByChannel(entries: CombatLogEntry[], channel: CombatLogChannel): CombatLogEntry[] {
    return filterLogEntriesByChannel(entries, channel);
  }

  /**
   * Helper to tokenize a message for rich tag rendering.
   */
  static tokenize(message: string): ParsedMessageToken[] {
    return tokenizeMessageWithTags(message);
  }
}
