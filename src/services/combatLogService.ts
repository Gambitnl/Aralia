/**
 * @file src/services/combatLogService.ts
 *
 * This file provides the central service for managing combat log entries, rich message channels,
 * event classification, and structured resistance/vulnerability/immunity metadata tags.
 *
 * In the Aralia combat system, events are generated by various engine hooks and commands
 * (such as attacks, spells, heals, status effects, and round transitions). This service
 * categorizes those events into user-friendly channels (all, damage, healing, conditions,
 * spells, narrative/system), attaches rich metadata tags (e.g. [Resisted: Fire (-50%)],
 * [Vulnerable: Radiant (+100%)], [Immune: Poison]), and provides filtering and tokenizing
 * utilities for UI renderers.
 *
 * Called by: CombatLog components (for filtering and pill rendering), combatLogToMessageAdapter,
 *            and combat engines.
 * Depends on: src/types/combat.ts, src/types/combatMessages.ts, src/utils/combat/resistanceUtils.ts
 */

